#!/usr/bin/env python3
"""Write the package-manager manifests for a published release.

    python3 packaging/release_manifests.py --version 0.1.0 --dist dist \\
        --repo irori-app/irori --output manifests

Reads the release's archives from `--dist` for their checksums and writes:

- `aur/PKGBUILD`: `irori-bin` and `irori-sign-in-bin`, from the Linux tarball;
- `homebrew/Casks/irori.rb`: the cask, from both macOS disk images;
- `scoop/bucket/irori.json`: the Scoop manifest, from the Windows zip.
"""
import argparse
import hashlib
import json
from pathlib import Path


HOMEPAGE = "https://irori.app"


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as file:
        for block in iter(lambda: file.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def artifacts(version: str, dist: Path) -> dict[str, Path]:
    names = {
        "linux": f"Irori-{version}-linux.tar.gz",
        "macos-arm64": f"Irori-{version}-macos-arm64.dmg",
        "macos-x86_64": f"Irori-{version}-macos-x86_64.dmg",
        "windows": f"Irori-{version}-windows.zip",
    }
    found = {key: dist / name for key, name in names.items()}
    missing = [path.name for path in found.values() if not path.is_file()]
    if missing:
        raise FileNotFoundError(f"Missing release archives in {dist}: {', '.join(missing)}")
    return found


PKGBUILD = """\
# Maintainer: Irori developers <https://github.com/{repo}>
# Generated by packaging/release_manifests.py for each release.
pkgbase=irori-bin
pkgname=(irori-bin irori-sign-in-bin)
pkgver={version}
pkgrel=1
pkgdesc="Every game you own, around one fire"
arch=(x86_64)
url="{homepage}"
license=(GPL-3.0-or-later)
options=(!strip !debug)
source=("Irori-$pkgver-linux.tar.gz::https://github.com/{repo}/releases/download/v$pkgver/Irori-$pkgver-linux.tar.gz")
sha256sums=('{linux_sha}')

package_irori-bin() {{
  depends=(gcc-libs glibc fontconfig freetype2 libxkbcommon libxkbcommon-x11 libxcb wayland
           vulkan-icd-loader systemd-libs)
  optdepends=('irori-sign-in-bin: sign in to stores in a window instead of the browser'
              'umu-launcher: run Windows games with umu'
              'wine: run Windows games with the system Wine'
              'gamemode: GameMode while playing'
              'mangohud: MangoHud overlay')
  provides=(irori)
  conflicts=(irori)
  cd Irori
  install -Dm755 irori "$pkgdir/usr/bin/irori"
  install -Dm644 irori.desktop "$pkgdir/usr/share/applications/irori.desktop"
  install -Dm644 irori.svg "$pkgdir/usr/share/icons/hicolor/scalable/apps/irori.svg"
  install -Dm644 app.irori.Irori.metainfo.xml \\
    "$pkgdir/usr/share/metainfo/app.irori.Irori.metainfo.xml"
  install -Dm644 LICENSE "$pkgdir/usr/share/licenses/$pkgname/LICENSE"
}}

package_irori-sign-in-bin() {{
  pkgdesc="Irori's store sign-in window"
  depends=(gtk3 webkit2gtk-4.1)
  provides=(irori-sign-in)
  conflicts=(irori-sign-in)
  cd Irori
  install -Dm755 irori-sign-in "$pkgdir/usr/bin/irori-sign-in"
  install -Dm644 LICENSE "$pkgdir/usr/share/licenses/$pkgname/LICENSE"
}}
"""

CASK = """\
# Generated by packaging/release_manifests.py in {repo} for each release.
cask "irori" do
  arch arm: "arm64", intel: "x86_64"

  version "{version}"
  sha256 arm:   "{arm_sha}",
         intel: "{intel_sha}"

  url "https://github.com/{repo}/releases/download/v#{{version}}/Irori-#{{version}}-macos-#{{arch}}.dmg"
  name "Irori"
  desc "Game launcher for Epic Games, GOG, Amazon Games, itch.io and emulators"
  homepage "{homepage}"

  livecheck do
    url :url
    strategy :github_latest
  end

  depends_on macos: ">= :monterey"

  app "Irori.app"

  zap trash: [
    "~/Library/Application Support/irori",
    "~/Library/Caches/irori",
  ]
end
"""


def scoop(version: str, repo: str, windows_sha: str) -> str:
    base = f"https://github.com/{repo}/releases/download"
    manifest = {
        "version": version,
        "description": "Every game you own, around one fire: Epic Games, GOG, Amazon Games, itch.io and emulators",
        "homepage": HOMEPAGE,
        "license": "GPL-3.0-or-later",
        "architecture": {"64bit": {
            "url": f"{base}/v{version}/Irori-{version}-windows.zip",
            "hash": windows_sha,
            "extract_dir": "Irori",
        }},
        "bin": "irori.exe",
        "shortcuts": [["irori.exe", "Irori"]],
        "checkver": {"github": f"https://github.com/{repo}"},
        "autoupdate": {"architecture": {"64bit": {
            "url": f"{base}/v$version/Irori-$version-windows.zip",
            "extract_dir": "Irori",
        }}},
    }
    return json.dumps(manifest, indent=4) + "\n"


def render(version: str, dist: Path, repo: str) -> dict[str, str]:
    """Manifest contents keyed by their path under the output folder."""
    found = artifacts(version, dist)
    return {
        "aur/PKGBUILD": PKGBUILD.format(version=version, repo=repo, homepage=HOMEPAGE, linux_sha=sha256(found["linux"])),
        "homebrew/Casks/irori.rb": CASK.format(
            version=version, repo=repo, homepage=HOMEPAGE,
            arm_sha=sha256(found["macos-arm64"]), intel_sha=sha256(found["macos-x86_64"])),
        "scoop/bucket/irori.json": scoop(version, repo, sha256(found["windows"])),
    }


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--version", required=True)
    parser.add_argument("--dist", type=Path, required=True)
    parser.add_argument("--repo", required=True, help="owner/name on GitHub")
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    for relative, content in render(args.version.removeprefix("v"), args.dist, args.repo).items():
        path = args.output / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
        print(path)
